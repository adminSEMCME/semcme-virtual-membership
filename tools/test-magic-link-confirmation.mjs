import assert from 'node:assert/strict';
import {prepareMagicLink} from '../public/magic-link.js';
const calls=[];
const options={token:'test-token',clearUrl:()=>calls.push('clear'),showStatus:()=>{},verify:async token=>{assert.equal(token,'test-token');calls.push('verify');},signedIn:()=>calls.push('signed-in')};
assert.equal(await prepareMagicLink(options),true);
assert.deepEqual(calls,['clear','verify','signed-in'],'opens library automatically with no additional click');
let error='';
await prepareMagicLink({...options,verify:async()=>{throw Error('Expired link');},showStatus:message=>error=message});
assert.equal(error,'Expired link');
assert.equal(await prepareMagicLink({...options,token:''}),false);
assert.equal(calls.filter(c=>c==='signed-in').length,1);
console.log('PASS: automatic sign-in, token removed from address bar before verification, expired-link feedback, and ordinary login without a token.');
